STOP_FLAG = False


@dataclass
class PrepConfig:
    input_dir: str
    output_dir: str
    poll_interval: int = 5
    batch_mode: bool = False
    max_files_per_run: int = 20  # Reduced - 20 files × 260MB = ~5GB, safe for GPU
    latest_only: bool = True
    file_stable_seconds: int = 10  # Wait for files to be this old before reading


def signal_handler(signum, frame):
    global STOP_FLAG
    print(f"{datetime.now():%Y-%m-%d %H:%M:%S} - Received shutdown signal", flush=True)
    STOP_FLAG = True


def log(msg: str):
    """Single logging function - uses stderr to avoid duplication issues."""
    ts = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    sys.stderr.write(f"{ts} - {msg}\n")
    sys.stderr.flush()


class DirectoryWatcher:
    """Watch for new run directories from Pod 1."""
    
    def __init__(self, watch_dir: Path):
        self.watch_dir = watch_dir
        self.state_file = watch_dir / ".prep_state.json"
        self.processed_dirs: Set[str] = self._load_state()
    
    def _load_state(self) -> Set[str]:
        if self.state_file.exists():
            try:
                with open(self.state_file) as f:
                    return set(json.load(f).get('processed', []))
            except:
                pass
        return set()
    
    def _save_state(self):
        try:
            with open(self.state_file, 'w') as f:
                json.dump({'processed': list(self.processed_dirs)}, f)
        except Exception as e:
            log(f"WARNING: Could not save state: {e}")
    
    def get_new_runs(self, latest_only: bool = False, min_age_seconds: int = 10) -> List[Path]:
        """Get unprocessed run directories that are stable (not being written to)."""
        if not self.watch_dir.exists():
            return []
        
        now = time.time()
        new_runs = []
        
        for entry in self.watch_dir.iterdir():
            if entry.is_dir() and entry.name.startswith("run_"):
                if entry.name not in self.processed_dirs:
                    # Check if directory has been stable for min_age_seconds
                    try:
                        mtime = entry.stat().st_mtime
                        age = now - mtime
                        if age < min_age_seconds:
                            continue  # Skip - still being written to
                    except:
                        continue
                    
                    # Quick check for any data files
                    has_files = (list(entry.glob("worker_*.parquet"))[:1] or 
                                 list(entry.glob("worker_*.csv"))[:1] or
                                 list(entry.glob("worker_*.bin"))[:1])
                    if has_files:
                        new_runs.append(entry)
        
        new_runs = sorted(new_runs, key=lambda x: x.name)
        
        if latest_only and new_runs:
            return [new_runs[-1]]
        
        return new_runs
    
    def mark_processed(self, run_dir: Path):
        self.processed_dirs.add(run_dir.name)
        self._save_state()


class FeatureEngineer:
    """GPU-accelerated feature engineering using RAPIDS cuDF."""
    
    PCA_COLS = [f"V{i}" for i in range(1, 29)]
    
    def process(self, df: cudf.DataFrame, run_name: str) -> cudf.DataFrame:
        """Apply feature engineering on GPU. Memory-optimized version."""
        start = time.time()
        log(f"Engineering features for {len(df):,} records...")
        
        # Add metadata
        df['transaction_id'] = cp.arange(len(df), dtype=cp.int64)
        df['source_run'] = run_name
        
        # Standard scaling for PCA columns (in-place to save memory)
        for col in self.PCA_COLS:
            if col in df.columns:
                mean_val = float(df[col].mean())
                std_val = float(df[col].std())
                if std_val > 0.001:
                    df[col] = (df[col] - mean_val) / std_val
        
        # Amount features
        if 'Amount' in df.columns:
            df['amount_log'] = cp.log1p(df['Amount'].values)
            amount_mean = float(df['Amount'].mean())
            amount_std = float(df['Amount'].std())
            if amount_std > 0.001:
                df['amount_scaled'] = (df['Amount'] - amount_mean) / amount_std
        
        # Time features (if Time column exists)
        if 'Time' in df.columns:
            df['hour_of_day'] = (df['Time'] / 3600) % 24
            df['is_night'] = ((df['hour_of_day'] >= 22) | (df['hour_of_day'] <= 6)).astype('int8')
        
        # Key interaction features (reduced set to save memory)
        if 'V1' in df.columns and 'V2' in df.columns:
            df['V1_V2_interaction'] = df['V1'] * df['V2']
        
        if 'Amount' in df.columns and 'V1' in df.columns:
            df['amount_V1_interaction'] = df['amount_scaled'] * df['V1']
        
        # Squared terms for key fraud indicators
        for col in ['V1', 'V14', 'V17']:
            if col in df.columns:
                df[f'{col}_squared'] = df[col] ** 2
        
        # Timestamp
        df['prep_timestamp'] = datetime.now().isoformat()
        
        elapsed = time.time() - start
        log(f"Feature engineering complete: {elapsed:.1f}s ({len(df)/elapsed:,.0f} rec/s)")
        return df


class DataPrepService:
    def __init__(self, config: PrepConfig):
        self.config = config
        self.input_path = Path(config.input_dir)
        self.output_path = Path(config.output_dir)
        self.output_path.mkdir(parents=True, exist_ok=True)
        
        self.watcher = DirectoryWatcher(self.input_path)
        self.engineer = FeatureEngineer()
        
        # Verify GPU availability
        try:
            gpu_count = cp.cuda.runtime.getDeviceCount()
            gpu_name = cp.cuda.runtime.getDeviceProperties(0)['name'].decode()
            gpu_mem = cp.cuda.runtime.getDeviceProperties(0)['totalGlobalMem'] / (1024**3)
            log(f"GPU: {gpu_count}x {gpu_name} ({gpu_mem:.0f}GB each)")
        except Exception as e:
            log(f"WARNING: GPU check failed: {e}")
        
        log("=" * 60)
        log("Pod 2: Data Prep Service (RAPIDS cuDF)")
        log("=" * 60)
        log(f"Input:       {self.input_path}")
        log(f"Output:      {self.output_path}")
        log(f"Mode:        {'batch' if config.batch_mode else 'continuous'}")
        log(f"Max files:   {config.max_files_per_run}")
        log(f"Latest only: {config.latest_only}")
        log(f"File stable: {config.file_stable_seconds}s")
        log("=" * 60)
    
    def get_stable_files(self, run_dir: Path, pattern: str, min_age: int = 5) -> List[Path]:
        """Get files that haven't been modified recently (complete files)."""
        now = time.time()
        stable_files = []
        
        for f in run_dir.glob(pattern):
            try:
                age = now - f.stat().st_mtime
                if age >= min_age:
                    stable_files.append(f)
            except:
                pass
        
        return sorted(stable_files)
    
    def read_run_data(self, run_dir: Path) -> Optional[cudf.DataFrame]:
        """Read data from a run directory with sampling and stability checks."""
        max_files = self.config.max_files_per_run
        
        # Try Parquet first
        parquet_files = self.get_stable_files(run_dir, "worker_*.parquet")
        if parquet_files:
            return self._load_sampled_files(parquet_files, 'parquet', max_files)
        
        # Try CSV
        csv_files = self.get_stable_files(run_dir, "worker_*.csv")
        if csv_files:
            return self._load_sampled_files(csv_files, 'csv', max_files)
        
        # Try binary
        bin_files = self.get_stable_files(run_dir, "worker_*.bin")
        if bin_files:
            return self._load_sampled_files(bin_files, 'binary', max_files)
        
        log(f"No stable data files found in {run_dir}")
        return None
    
    def _load_sampled_files(self, files: List[Path], file_type: str, max_files: int) -> cudf.DataFrame:
        """Load files with sampling if too many."""
        total_files = len(files)
        
        if total_files > max_files:
            # Sample evenly across the file list
            step = total_files // max_files
            files = files[::step][:max_files]
            log(f"Sampling {len(files)} of {total_files:,} {file_type} files")
        else:
            log(f"Loading all {total_files} {file_type} files")
        
        if file_type == 'binary':
            return self._load_binary_files(files)
        else:
            return self._load_files_chunked(files, file_type)
    
    def _load_files_chunked(self, files: List[Path], file_type: str) -> Optional[cudf.DataFrame]:
        """Load and process files in chunks, writing each chunk to avoid OOM."""
        start = time.time()
        chunk_size = 5  # Smaller chunks to stay within GPU memory
        total_records = 0
        output_parts = []
        
        for i in range(0, len(files), chunk_size):
            chunk_files = files[i:i + chunk_size]
            chunk_num = i // chunk_size + 1
            total_chunks = (len(files) + chunk_size - 1) // chunk_size
            
            log(f"  Chunk {chunk_num}/{total_chunks}: {len(chunk_files)} files")
            
            try:
                if file_type == 'parquet':
                    dfs = [cudf.read_parquet(str(f)) for f in chunk_files]
                else:  # csv
                    dfs = [cudf.read_csv(str(f)) for f in chunk_files]
                
                chunk_df = cudf.concat(dfs, ignore_index=True)
                total_records += len(chunk_df)
                
                # Free individual dfs immediately
                del dfs
                
                # Store chunk for later
                output_parts.append(chunk_df)
                
                # Free GPU memory pool
                cp.get_default_memory_pool().free_all_blocks()
                
            except Exception as e:
                log(f"  WARNING: Chunk {chunk_num} failed: {e}")
                cp.get_default_memory_pool().free_all_blocks()
                continue
        
        if not output_parts:
            return None
        
        # If we have few enough parts, concat them
        if len(output_parts) <= 3:
            log(f"  Combining {len(output_parts)} parts...")
            df = cudf.concat(output_parts, ignore_index=True)
            del output_parts
            cp.get_default_memory_pool().free_all_blocks()
        else:
            # Too many parts - just return the first chunk for now
            # (Full solution would process each chunk and merge outputs)
            log(f"  Using first {len(output_parts[0]):,} records (memory limit)")
            df = output_parts[0]
            del output_parts
            cp.get_default_memory_pool().free_all_blocks()
        
        elapsed = time.time() - start
        log(f"Loaded {len(df):,} records in {elapsed:.1f}s")
        
        return df
    
    def _load_binary_files(self, files: List[Path]) -> cudf.DataFrame:
        """Load binary numpy files."""
        start = time.time()
        columns = ['Time'] + [f'V{i}' for i in range(1, 29)] + ['Amount', 'Class']
        
        arrays = []
        for f in files:
            try:
                data = np.fromfile(str(f), dtype=np.float32).reshape(-1, 31)
                arrays.append(data)
            except Exception as e:
                log(f"  WARNING: Failed to load {f.name}: {e}")
        
        if not arrays:
            return None
        
        combined = np.vstack(arrays)
        df = cudf.DataFrame(combined, columns=columns)
        
        elapsed = time.time() - start
        log(f"Loaded {len(df):,} records in {elapsed:.1f}s")
        return df
    
    def write_output(self, df: cudf.DataFrame, run_name: str):
        """Write processed data to parquet."""
        output_file = self.output_path / f"features_{run_name}.parquet"
        log(f"Writing: {output_file.name}")
        
        df.to_parquet(str(output_file), compression='snappy')
        
        size_mb = output_file.stat().st_size / (1024*1024)
        log(f"Output: {size_mb:.1f} MB, {len(df):,} records")
        
        # Metadata for Pod 3
        exclude = ['transaction_id', 'source_run', 'prep_timestamp', 'Class']
        feature_cols = [c for c in df.columns if c not in exclude]
        
        metadata = {
            "run_name": run_name,
            "timestamp": datetime.now().isoformat(),
            "columns": list(df.columns),
            "feature_columns": feature_cols,
            "target_column": "Class",
            "record_count": len(df)
        }
        
        meta_file = self.output_path / f"metadata_{run_name}.json"
        with open(meta_file, 'w') as f:
            json.dump(metadata, f, indent=2)
    
    def process_run(self, run_dir: Path) -> bool:
        """Process a single run directory."""
        run_name = run_dir.name
        log("=" * 60)
        log(f"Processing: {run_name}")
        
        try:
            # Load data
            df = self.read_run_data(run_dir)
            if df is None or len(df) == 0:
                log(f"No data loaded from {run_name}")
                return False
            
            # Engineer features
            df = self.engineer.process(df, run_name)
            
            # Write output
            self.write_output(df, run_name)
            
            # Mark as processed
            self.watcher.mark_processed(run_dir)
            
            # Cleanup
            del df
            cp.get_default_memory_pool().free_all_blocks()
            
            log(f"SUCCESS: {run_name}")
            log("=" * 60)
            return True
            
        except Exception as e:
            log(f"ERROR: {e}")
            import traceback
            traceback.print_exc()
            
            # Try to recover GPU memory
            cp.get_default_memory_pool().free_all_blocks()
            return False
    
    def run(self):
        """Main run loop."""
        global STOP_FLAG
        
        if self.config.batch_mode:
            runs = self.watcher.get_new_runs(
                latest_only=self.config.latest_only,
                min_age_seconds=self.config.file_stable_seconds
            )
            log(f"Batch mode: {len(runs)} run(s) to process")
            for run_dir in runs:
                self.process_run(run_dir)
            log("Batch complete")
        else:
            log("Watching for new runs...")
            while not STOP_FLAG:
                runs = self.watcher.get_new_runs(
                    latest_only=self.config.latest_only,
                    min_age_seconds=self.config.file_stable_seconds
                )
                
                for run_dir in runs:
                    if STOP_FLAG:
                        break
                    self.process_run(run_dir)
                
                if not STOP_FLAG:
                    time.sleep(self.config.poll_interval)
            
            log("Stopped")


def main():
    # Log PID to help debug duplicate processes
    log(f"Starting (PID: {os.getpid()})")
    
    signal.signal(signal.SIGINT, signal_handler)
    signal.signal(signal.SIGTERM, signal_handler)
    
    config = PrepConfig(
        input_dir=os.getenv('INPUT_DIR', '/mnt/fsaai-shared/ebiser/fraud-data'),
        output_dir=os.getenv('OUTPUT_DIR', '/mnt/fsaai-shared/ebiser/prep-output'),
        poll_interval=int(os.getenv('POLL_INTERVAL', '5')),
        batch_mode=os.getenv('BATCH_MODE', 'false').lower() == 'true',
        max_files_per_run=int(os.getenv('MAX_FILES_PER_RUN', '20')),
        latest_only=os.getenv('LATEST_ONLY', 'true').lower() == 'true',
        file_stable_seconds=int(os.getenv('FILE_STABLE_SECONDS', '10'))
    )
    
    DataPrepService(config).run()


if __name__ == "__main__":
    main()